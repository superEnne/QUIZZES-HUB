  ("SOAP Fault vs. REST error", "SOAP = Fault inside the Body. REST = status code plus a JSON body."),
  ("PUT vs. PATCH", "PUT = replace the whole resource (idempotent). PATCH = modify part of it."),
  ("Safe vs. Idempotent", "Safe = never changes data (GET). Idempotent = same final effect when repeated (GET, PUT, DELETE)."),
  ("401 vs. 403", "401 = we do not know who you are. 403 = we know you, but you are not allowed."),
  ("Serialization vs. Deserialization", "Serialization = object to text or bytes. Deserialization = text or bytes back to an object."),
  ("Encryption vs. Hashing", "Encryption = reversible with a key, confidentiality. Hashing = one-way fingerprint, integrity, used for passwords."),
